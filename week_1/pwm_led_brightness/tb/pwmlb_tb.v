`timescale 1ns / 1ps

module pwm_led_tb;

    // --------------------------------------------------------
    // Testbench signals
    // --------------------------------------------------------
    reg        clk;
    reg [3:0]  btn;
    wire       led;

    // --------------------------------------------------------
    // DUT
    // --------------------------------------------------------
    pwm_led dut (
        .clk (clk),
        .btn (btn),
        .led (led)
    );

    // --------------------------------------------------------
    // 125 MHz clock
    // Period = 8 ns
    // --------------------------------------------------------
    initial begin
        clk = 1'b0;

        forever #4 clk = ~clk;
    end

    // --------------------------------------------------------
    // Test sequence
    // --------------------------------------------------------
    initial begin

        // Initial state
        btn = 4'b0000;

        #20;

        // ----------------------------------------------------
        // Test 25% duty cycle
        // ----------------------------------------------------
        $display("========================================");
        $display("Testing 25%% Duty Cycle");
        $display("========================================");

        btn = 4'b0001;

        // Wait for 2 complete PWM periods
        #4096;

        // ----------------------------------------------------
        // Test 50% duty cycle
        // ----------------------------------------------------
        $display("========================================");
        $display("Testing 50%% Duty Cycle");
        $display("========================================");

        btn = 4'b0010;

        #4096;

        // ----------------------------------------------------
        // Test 75% duty cycle
        // ----------------------------------------------------
        $display("========================================");
        $display("Testing 75%% Duty Cycle");
        $display("========================================");

        btn = 4'b0100;

        #4096;

        // ----------------------------------------------------
        // Test 100% duty cycle
        // ----------------------------------------------------
        $display("========================================");
        $display("Testing 100%% Duty Cycle");
        $display("========================================");

        btn = 4'b1000;

        #4096;

        // ----------------------------------------------------
        // Test default condition
        // ----------------------------------------------------
        $display("========================================");
        $display("Testing Default Condition");
        $display("========================================");

        btn = 4'b0000;

        #4096;

        // ----------------------------------------------------
        // Finish simulation
        // ----------------------------------------------------
        $display("========================================");
        $display("PWM TEST COMPLETE");
        $display("========================================");

        $finish;

    end

endmodule