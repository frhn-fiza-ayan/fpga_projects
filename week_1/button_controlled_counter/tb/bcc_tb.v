`timescale 1ns / 1ps

module button_controlled_counter_tb;

    // Inputs
    reg clk;
    reg btn;

    // Output
    wire [3:0] led;

    // =========================================================
    // DUT - Device Under Test
    // =========================================================

    button_controlled_counter #(
        .DEBOUNCE_COUNT(5)
    ) uut (
        .clk(clk),
        .btn(btn),
        .led(led)
    );

    // =========================================================
    // CLOCK
    // 10 ns period = 100 MHz simulation clock
    // =========================================================

    always #5 clk = ~clk;

    // =========================================================
    // TEST
    // =========================================================

    initial begin

        // Initial values
        clk = 0;
        btn = 0;

        // Wait
        #100;

        // -----------------------------------------------------
        // PRESS BUTTON #1
        // -----------------------------------------------------

        btn = 1;
        #100;

        // Release
        btn = 0;
        #100;

        // -----------------------------------------------------
        // PRESS BUTTON #2
        // -----------------------------------------------------

        btn = 1;
        #100;

        // Release
        btn = 0;
        #100;

        // -----------------------------------------------------
        // PRESS BUTTON #3
        // -----------------------------------------------------

        btn = 1;
        #100;

        // Release
        btn = 0;
        #100;

        // -----------------------------------------------------
        // HOLD BUTTON
        // LED should NOT keep counting
        // -----------------------------------------------------

        btn = 1;
        #300;

        // Release
        btn = 0;
        #100;

        // -----------------------------------------------------
        // PRESS BUTTON #4
        // -----------------------------------------------------

        btn = 1;
        #100;

        // Release
        btn = 0;
        #100;

        // Finish simulation
        $finish;

    end

endmodule