`timescale 1ns / 1ps

module button_debouncer_tb;

    reg clk;
    reg btn;
    wire debounced_btn;

    // ============================================================
    // DUT
    // Use a small count for simulation
    // ============================================================

    button_debouncer #(
        .DEBOUNCE_COUNT(5)
    ) uut (
        .clk(clk),
        .btn(btn),
        .debounced_btn(debounced_btn)
    );

    // ============================================================
    // 100 MHz simulation clock
    // 10 ns period
    // ============================================================

    always #5 clk = ~clk;


    // ============================================================
    // Test
    // ============================================================

    initial begin

        clk = 0;
        btn = 0;

        // --------------------------------------------------------
        // Initial state
        // --------------------------------------------------------

        #100;


        // --------------------------------------------------------
        // Button press with bouncing
        // --------------------------------------------------------

        btn = 1;
        #20;

        btn = 0;
        #20;

        btn = 1;
        #20;

        btn = 0;
        #20;

        btn = 1;


        // --------------------------------------------------------
        // Keep button stable
        // Debouncer should eventually output 1
        // --------------------------------------------------------

        #150;


        // --------------------------------------------------------
        // Button release with bouncing
        // --------------------------------------------------------

        btn = 0;
        #20;

        btn = 1;
        #20;

        btn = 0;
        #20;

        btn = 1;
        #20;

        btn = 0;


        // --------------------------------------------------------
        // Keep button stable
        // Debouncer should eventually output 0
        // --------------------------------------------------------

        #150;


        $finish;

    end

endmodule